let currentLang = localStorage.getItem('fs_lang') || 'es';

function t(key) {
  return TRANSLATIONS[currentLang][key] || TRANSLATIONS['en'][key] || key;
}

function setLang(lang) {
  currentLang = lang;
  localStorage.setItem('fs_lang', lang);
  document.querySelectorAll('.lang-sel button').forEach(b => {
    b.classList.toggle('active', b.dataset.lang === lang);
  });
  applyTranslations();
}

function applyTranslations() {
  document.querySelectorAll('[data-t]').forEach(el => {
    const key = el.dataset.t;
    el.textContent = t(key);
  });
  document.querySelectorAll('[data-t-ph]').forEach(el => {
    el.placeholder = t(el.dataset.tPh);
  });
  // Campos con HTML (negrita, etc.)
  const p3 = document.getElementById('about_p3_el');
  if (p3) p3.innerHTML = t('about_p3');
  if (typeof onLangChange === 'function') onLangChange();
}

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-sel button').forEach(b => {
    b.addEventListener('click', () => setLang(b.dataset.lang));
    b.classList.toggle('active', b.dataset.lang === currentLang);
  });
  applyTranslations();
});
